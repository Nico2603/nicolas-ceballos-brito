#!/usr/bin/env node
/**
 * Materialize gitignored .env.local from Cursor Cloud Runtime Secrets.
 * Only writes keys listed in .env.example (never VERCEL_TOKEN / service_role).
 * Never prints secret values.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const examplePath = join(root, '.env.example')
const localPath = join(root, '.env.local')
const bindingPath = join(root, '.deploy/binding.json')
const probe = process.argv.includes('--probe')

function keysFromExample(text) {
  const keys = []
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#') || !line.includes('=')) continue
    keys.push(line.split('=')[0].trim())
  }
  return keys
}

function parseEnvFile(text) {
  /** @type {Map<string, string>} */
  const map = new Map()
  for (const raw of text.split(/\r?\n/)) {
    if (!raw || raw.trim().startsWith('#')) continue
    const eq = raw.indexOf('=')
    if (eq <= 0) continue
    const key = raw.slice(0, eq).trim()
    let value = raw.slice(eq + 1)
    if (value.startsWith('"') && value.endsWith('"')) {
      value = value.slice(1, -1).replace(/\\n/g, '\n').replace(/\\r/g, '\\r').replace(/\\"/g, '"').replace(/\\\\/g, '\\')
    }
    map.set(key, value)
  }
  return map
}

function encodeEnvValue(value) {
  if (/[\n\r"#\\]/.test(value) || /^\s|\s$/.test(value)) {
    return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '\\r').replace(/\n/g, '\\n')}"`
  }
  return value
}

function loadBinding() {
  if (!existsSync(bindingPath)) return null
  try {
    return JSON.parse(readFileSync(bindingPath, 'utf8'))
  } catch {
    return null
  }
}

const exampleKeys = existsSync(examplePath)
  ? keysFromExample(readFileSync(examplePath, 'utf8'))
  : []

if (probe) {
  const binding = loadBinding()
  /** @type {string[]} */
  const names = [...exampleKeys]
  if (binding?.vercel?.enabled) names.push('VERCEL_TOKEN')
  if (binding?.supabase?.enabled) {
    names.push('SUPABASE_ACCESS_TOKEN', 'SUPABASE_SERVICE_ROLE_KEY')
  }
  if (!binding) {
    for (const name of [
      'CASA_SUPABASE_URL',
      'CASA_SUPABASE_ANON_KEY',
      'CASA_SUPABASE_SERVICE_ROLE_KEY',
      'CASA_SUPABASE_ACCESS_TOKEN',
    ]) {
      if (!names.includes(name)) names.push(name)
    }
  }
  for (const name of names) {
    console.log(`${name}=${process.env[name] ? 'set' : 'missing'}`)
  }
  process.exit(0)
}

if (exampleKeys.length === 0) {
  console.log('write-cloud-env: no .env.example keys; skip')
  process.exit(0)
}

const incoming = exampleKeys.filter((key) => process.env[key])
if (incoming.length === 0) {
  console.log('write-cloud-env: no listed secrets in env; skip')
  process.exit(0)
}

const merged = existsSync(localPath)
  ? parseEnvFile(readFileSync(localPath, 'utf8'))
  : new Map()

for (const key of incoming) {
  merged.set(key, process.env[key] ?? '')
}

const lines = ['# Generated by scripts/write-cloud-env.mjs — do not commit']
for (const [key, value] of merged) {
  lines.push(`${key}=${encodeEnvValue(value)}`)
}
writeFileSync(localPath, `${lines.join('\n')}\n`, { encoding: 'utf8', mode: 0o600 })
console.log(`write-cloud-env: wrote ${incoming.length} key(s) into .env.local`)
